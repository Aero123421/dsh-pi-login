import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve, join } from 'node:path'

async function packageFor(file) {
  let folder = dirname(resolve(file))
  while (folder !== dirname(folder)) {
    try {
      const manifest = JSON.parse(await readFile(join(folder, 'package.json'), 'utf8'))
      if (manifest.name) return { folder, manifest }
    } catch {}
    folder = dirname(folder)
  }
}

/** Include license/notice texts for every package represented in the Host graph. */
export async function writeBundleNotices(metafile, outfile = 'dist/THIRD_PARTY_NOTICES.txt') {
  const packages = new Map()
  for (const file of Object.keys(metafile.inputs)) {
    if (!file.includes('node_modules/')) continue
    const pkg = await packageFor(file)
    if (!pkg) throw new Error(`No package metadata for bundled module: ${file}`)
    packages.set(`${pkg.manifest.name}@${pkg.manifest.version}`, pkg)
  }
  const sections = ['Bundled Host dependencies\nGenerated by scripts/bundle-notices.mjs from the esbuild module graph.\n']
  for (const [id, { folder, manifest }] of [...packages].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const files = (await readdir(folder)).filter(name => /^(?:licen[cs]e|notice|copyright)(?:[.\-_].*)?$/i.test(name)).sort()
    const texts = []
    for (const name of files) {
      try { texts.push(`${name}\n${await readFile(join(folder, name), 'utf8')}`) }
      catch (error) { if (error.code !== 'EISDIR') throw error }
    }
    if (!texts.length) {
      const fallback = manifest.name.startsWith('@aws-sdk/') ? 'aws-sdk'
        : manifest.name.startsWith('@earendil-works/pi-') ? 'pi-ai'
        : manifest.name === 'proxy-agent-negotiate' ? 'proxy-agents'
        : manifest.name === 'standardwebhooks' ? 'standardwebhooks' : undefined
      if (fallback) texts.push(`LICENSE (upstream repository; see licenses/README.md)\n${await readFile(`licenses/${fallback}-LICENSE.txt`, 'utf8')}`)
      if (manifest.name === 'data-uri-to-buffer') {
        const readme = await readFile(join(folder, 'README.md'), 'utf8')
        const start = readme.indexOf('(The MIT License)')
        if (start !== -1) texts.push(`LICENSE (package README)\n${readme.slice(start)}`)
      }
    }
    if (!texts.length) throw new Error(`No license text found for bundled dependency ${id}`)
    sections.push(`\n${'='.repeat(72)}\n${id}\nLicense: ${typeof manifest.license === 'string' ? manifest.license : JSON.stringify(manifest.license)}\n\n${texts.join('\n\n')}`)
  }
  await mkdir(dirname(outfile), { recursive: true })
  await writeFile(outfile, sections.join('\n'))
  return packages.size
}
